// Our own short UI cues, without game recordings or third-party samples.
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const destination = fileURLToPath(new URL('../../desktop/assets/menu-sounds/', import.meta.url));
const sampleRate = 22050;
const cues = { up: [640, 960, .045], down: [880, 620, .045], ok: [520, 1040, .09], cancel: [620, 280, .07] };
for (const pack of ['pulse', 'grain']) {
  const directory = path.join(destination, pack);
  await mkdir(directory, { recursive: true });
  for (const [name, [start, end, seconds]] of Object.entries(cues)) {
    const frames = Math.floor(sampleRate * seconds);
    const wav = Buffer.alloc(44 + frames * 2);
    wav.write('RIFF'); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8);
    wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22);
    wav.writeUInt32LE(sampleRate, 24); wav.writeUInt32LE(sampleRate * 2, 28);
    wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34); wav.write('data', 36); wav.writeUInt32LE(frames * 2, 40);
    let phase = 0;
    let held = 0;
    for (let frame = 0; frame < frames; frame++) {
      const t = frame / frames;
      const frequency = start + (end - start) * t;
      phase += frequency / sampleRate;
      const cycle = phase % 1;
      const wave = pack === 'pulse' ? (cycle < .35 ? 1 : -1) : Math.sin(phase * Math.PI * 2 + 2.1 * Math.sin(phase * Math.PI * 4));
      if (pack === 'pulse' || frame % 3 === 0) held = Math.round(wave * 15) / 15;
      const envelope = Math.min(1, frame / 70) * Math.pow(1 - t, 1.8);
      wav.writeInt16LE(Math.round(held * envelope * 4200), 44 + frame * 2);
    }
    await writeFile(path.join(directory, `${name}.wav`), wav);
  }
}
await writeFile(path.join(destination, 'PROVENANCE.txt'), 'Original ROM-in-a-Box procedural UI cues, generated by scripts/native_runtime/generate-menu-sounds.mjs. No game recordings or third-party audio. Project licensing remains to be selected.\n');
